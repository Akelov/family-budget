/**
 * Приводит название категории к ключу для сопоставления лимитов и операций:
 * обрезает пробелы по краям и переводит в нижний регистр по правилам ru-RU.
 * Так «Продукты», «продукты » и «ПРОДУКТЫ» считаются одной категорией.
 *
 * Пробелы внутри названия не схлопываются: «Кафе  и рестораны» с двумя
 * пробелами — другая категория, это ошибка ввода, а не вариант написания.
 *
 * @param category - название категории в произвольном написании
 * @returns ключ категории, например `"продукты"`
 * @throws {RangeError} если после `trim()` название пустое
 */
export function normalizeCategory(category: string): string {
  const normalized = category.trim().toLocaleLowerCase('ru-RU');
  if (normalized === '') {
    throw new RangeError('Название категории не может быть пустым');
  }
  return normalized;
}
